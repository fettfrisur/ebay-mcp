#!/usr/bin/env python3
"""Work out which eBay REST operations this keyset can call, from eBay's official OpenAPI contracts.

Usage: python3 scripts/build-api-surface.py [OUT_DIR]      (default: build/api-surface)
Needs: Python 3.9+, PyYAML (one contract is YAML). Optional: openapi-spec-validator.

Writes in OUT_DIR:
  specs/                          downloaded contracts (as published)
  operations.csv / .json          every operation with its access tier
  ebay-app-token-api.openapi.json merged OpenAPI 3.1 of tier-A operations only

Tiers: A = app token (client_credentials), no login; B = needs eBay user consent
(authorization_code) with the scopes granted to the app; X = not covered by granted scopes.
eBay convention: when an operation lists several scopes, ANY ONE suffices.
Update CC / AC below when the app's granted scopes change (see docs/api-surface/README.md).
"""
import copy, csv, json, os, re, sys, urllib.request, urllib.error
import yaml

OUT = sys.argv[1] if len(sys.argv) > 1 else "build/api-surface"
B = "https://api.ebay.com/oauth/api_scope"
CC = {B, B + "/commerce.feedback.readonly"}                       # Client Credential Grant scopes
AC = {B, *[B + "/" + s for s in """sell.marketing.readonly sell.marketing sell.inventory.readonly
  sell.inventory sell.account.readonly sell.account sell.fulfillment.readonly sell.fulfillment
  sell.analytics.readonly sell.finances sell.payment.dispute commerce.identity.readonly sell.reputation
  sell.reputation.readonly commerce.notification.subscription commerce.notification.subscription.readonly
  sell.stores sell.stores.readonly sell.inventory.mapping commerce.message commerce.feedback commerce.shipping
  sell.listing sell.listing.read sell.cancellation.read sell.cancellation sell.return.read sell.return
  sell.inquiry sell.inquiry.read commerce.post_order.document sell.offer commerce.vero""".split()],
      "https://api.ebay.com/oauth/scope/sell.edelivery"}          # Authorization Code Grant scopes

# local name -> published file name under https://developer.ebay.com/develop/api/spec/
SPECS = {n: f"{n}_api.json" for n in """developer_analytics key_management browse deal feed offer marketing message
  catalog charity identity media notification taxonomy translation feedback analytics finances fulfillment
  inventory logistics metadata negotiation recommendation stores edelivery_international_shipping leads
  post_order""".split()}
SPECS.update(account="account_api_v1.json", order="order_api_v1.json", vero="vero_api_v2.json",
             marketplace_insights="marketplace_insights_api.json")      # the last one is YAML
URL = "https://developer.ebay.com/develop/api/spec/"
HTTP = ("get", "put", "post", "delete", "patch")

def fetch(name, fn, d):
    path = os.path.join(d, name + (".yaml" if name == "marketplace_insights" else ".json"))
    if not os.path.exists(path):
        try:
            with urllib.request.urlopen(URL + fn, timeout=60) as r: open(path, "wb").write(r.read())
        except urllib.error.URLError as e:
            print("skip", name, e); return None
    t = open(path).read()
    return json.loads(t) if path.endswith(".json") else yaml.safe_load(t)

def classify(a, d):
    sch = d.get("components", {}).get("securitySchemes", {})
    cc_f = {s for x in sch.values() for s in x.get("flows", {}).get("clientCredentials", {}).get("scopes", {})} | {B}
    ac_f = {s for x in sch.values() for s in x.get("flows", {}).get("authorizationCode", {}).get("scopes", {})} | cc_f
    base = (d.get("servers") or [{}])[0].get("variables", {}).get("basePath", {}).get("default", "")
    for p, item in d["paths"].items():
        for m, op in item.items():
            if m not in HTTP: continue
            scopes = sorted({s for r in (op.get("security") or d.get("security") or []) for v in r.values() for s in v})
            tier = "A" if any(s in CC and s in cc_f for s in scopes) else \
                   "B" if any(s in AC and s in ac_f for s in scopes) else "X"
            yield dict(api=a, tier=tier, method=m.upper(), path=base + p, operationId=op.get("operationId"),
                       summary=op.get("summary"), scopes=[s.replace(B, "api_scope") for s in scopes], _p=p, _m=m)

def merge(specs, rows):
    out = {"openapi": "3.1.0",
           "info": {"title": "eBay operations reachable with an app token (client credentials)", "version": "generated",
                    "description": "Generated by scripts/build-api-surface.py from eBay's official contracts. Listed scopes are alternatives: any one suffices."},
           "servers": [{"url": "https://api.ebay.com"}], "paths": {},
           "components": {"schemas": {}, "responses": {}, "securitySchemes": {"ebay_app_token": {"type": "oauth2",
               "flows": {"clientCredentials": {"tokenUrl": "https://api.ebay.com/identity/v1/oauth2/token",
               "scopes": {B: "View public data from eBay", B + "/commerce.feedback.readonly": "Readonly Feedback API access"}}}}}}}
    ids = set(); ref = re.compile(r"#/components/(schemas|responses|parameters)/")
    for a in sorted({r["api"] for r in rows if r["tier"] == "A"}):
        d = specs[a]; pfx = re.sub(r"\W", "_", a) + "__"; s0 = d["servers"][0]
        base = s0.get("variables", {}).get("basePath", {}).get("default", ""); host = re.match(r"https://[^/{]+", s0["url"]).group(0)
        keep = {(r["_m"], r["_p"]) for r in rows if r["api"] == a and r["tier"] == "A"}; sub = {}
        for p, item in d["paths"].items():
            it = {k: v for k, v in item.items() if k in ("parameters", "summary", "description")}
            for m, op in item.items():
                if (m, p) in keep:
                    op = copy.deepcopy(op)
                    sc = [s for r in (op.get("security") or d.get("security") or []) for v in r.values() for s in v if s in CC]
                    op["security"] = [{"ebay_app_token": sc}]; op["tags"] = [a]
                    oid = op.get("operationId") or m + p
                    op["operationId"] = pfx + oid if oid in ids else oid; ids.add(op["operationId"]); it[m] = op
                    for prm in op.get("parameters", []):          # upstream defect: path param without "in"
                        if "in" not in prm and "{" + prm.get("name", "") + "}" in p: prm["in"] = "path"
            if any(m in it for m in HTTP):
                if host != "https://api.ebay.com": it["servers"] = [{"url": host}]
                sub[base + p] = it
        out["paths"].update(json.loads(ref.sub(lambda m: f"#/components/{m.group(1)}/{pfx}", json.dumps(sub))))
        for sec in ("schemas", "responses"):
            for k, v in d.get("components", {}).get(sec, {}).items():
                out["components"][sec][pfx + k] = json.loads(ref.sub(lambda m: f"#/components/{m.group(1)}/{pfx}", json.dumps(v)))
    used = set(re.findall(r"#/components/(schemas|responses)/([^\"]+)", json.dumps(out["paths"]))); todo = list(used)
    while todo:                                                    # keep only referenced components
        sec, k = todo.pop()
        for n in set(re.findall(r"#/components/(schemas|responses)/([^\"]+)", json.dumps(out["components"][sec].get(k, {})))) - used:
            used.add(n); todo.append(n)
    for sec in ("schemas", "responses"):
        out["components"][sec] = {k: v for k, v in out["components"][sec].items() if (sec, k) in used}
    def dedupe(o):                                                 # upstream defect: duplicate "required" entries
        if isinstance(o, dict):
            for k, v in o.items():
                if k == "required" and isinstance(v, list): o[k] = list(dict.fromkeys(v))
                else: dedupe(v)
        elif isinstance(o, list):
            for v in o: dedupe(v)
    dedupe(out); return out

def main():
    os.makedirs(os.path.join(OUT, "specs"), exist_ok=True)
    specs = {n: d for n, fn in SPECS.items() if (d := fetch(n, fn, os.path.join(OUT, "specs")))}
    rows = [r for a, d in specs.items() for r in classify(a, d)]
    pub = [{k: v for k, v in r.items() if not k.startswith("_")} for r in rows]
    json.dump(pub, open(os.path.join(OUT, "operations.json"), "w"), indent=1)
    with open(os.path.join(OUT, "operations.csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(["tier", "api", "method", "path", "operationId", "accepted_scopes_any_of"])
        for r in sorted(pub, key=lambda r: (r["tier"], r["api"], r["path"])):
            w.writerow([r["tier"], r["api"], r["method"], r["path"], r["operationId"], " | ".join(r["scopes"])])
    merged = merge(specs, rows)
    json.dump(merged, open(os.path.join(OUT, "ebay-app-token-api.openapi.json"), "w"), indent=1)
    from collections import Counter
    print("operations by tier:", dict(Counter(r["tier"] for r in rows)), "| merged paths:", len(merged["paths"]))
    try:
        from openapi_spec_validator import validate; validate(merged); print("merged spec validates as OpenAPI 3.1")
    except ImportError: print("(install openapi-spec-validator to validate)")

if __name__ == "__main__": main()
